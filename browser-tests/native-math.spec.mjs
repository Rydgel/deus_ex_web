import { test, expect } from '@playwright/test';

test('Chromium reconstructs the original sine table and brush coordinate capture exactly', async ({ page }) => {
  await page.goto('http://127.0.0.1:5173');
  const result = await page.evaluate(async () => {
    const { rotationSineTable, brushToWorld } = await import('/src/runtime/coords.mjs');
    const table = rotationSineTable(), bytes = new ArrayBuffer(table.length * 4), view = new DataView(bytes);
    table.forEach((value, i) => view.setFloat32(i * 4, value, true));
    const digest = await crypto.subtle.digest('SHA-256', bytes);
    return { hash: [...new Uint8Array(digest)].map(v => v.toString(16).padStart(2, '0')).join(''),
      coords: brushToWorld({ Location: [1317.25, -319.75, -77.125], PrePivot: [101, 7.5, -31],
        Rotation: [12345, -7987, 19999], MainScale: { scale: [2, .5, -3], shearAxis: 1, shearRate: -1 } }) };
  });
  // Original FGlobalMath table and ABrush.ToWorld case 52, captured independently
  // by native-coords-oracle.py. These expectations are not generated by JS math.
  expect(result.hash).toBe('9893d14bd21e5c4194832659571b30363ddfb08d468ed662a4b6d5ae172262dc');
  expect(result.coords).toEqual([262.20831298828125, -1623.918212890625, 308.9936218261719,
    -0.12276703119277954, 0.19626034796237946, -2.635568618774414,
    0.9185657501220703, -0.42417359352111816, -1.3805261850357056,
    2.455842971801758, -0.17764748632907867, 0.38461047410964966]);
});
