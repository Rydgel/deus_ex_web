// Build src/runtime/map-registry-seeds.mjs from the original GObjObjects
// captures (docs/object-index-captures.md "Runtime spawns"): per map, the
// registry's high-water mark (GObjObjects.Num, the header's objects=) and its
// holes (freed slots below it), in the same capture session as the map's
// measured indices (build-map-object-indices.mjs captureFor). A runtime spawn
// continues the AddObject rule from here: the last freed slot first (LIFO),
// else a new slot at the high-water mark. The dump gives the holes as a set,
// not the order they were freed in: the seed is exact for at most one hole,
// and the entry records how many (`holes`), so a consumer can say so.
//
//   node scripts/build-map-registry-seeds.mjs [--date yyyymmdd] [--check]
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gameDirectory } from './game-directory.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const argv = process.argv.slice(2);
const flag = (name, fallback) => { const i = argv.indexOf(name); return i < 0 ? fallback : argv[i + 1]; };
const date = flag('--date', '20261001'), check = argv.includes('--check');
const maps = (await readdir(path.join(gameDirectory(), 'Maps'))).filter(name => /\.dx$/i.test(name) && !/^dxmp_/i.test(name))
  .map(name => name.replace(/\.dx$/i, '').toLowerCase()).sort();
const captureFor = map => map === '00_training' ? path.join(root, '.cache', 'original-gobjects.txt')
  : path.join(root, '.cache', `original-gobjects-${date}-${map}-open.txt`);
const entries = [], report = [];
for (const map of maps) {
  const file = captureFor(map);
  if (!existsSync(file)) { report.push({ map, capture: false }); continue; }
  const text = await readFile(file, 'utf8');
  const count = Number(/objects=(\d+)/.exec(text.split('\n', 1)[0])?.[1]);
  const present = new Set();
  for (const line of text.split('\n')) { const m = /^slot\s+\d+\s+index\s+(\d+)\s/.exec(line); if (m) present.add(Number(m[1])); }
  if (!Number.isInteger(count) || [...present].some(index => index >= count)) throw new Error(`${map}: unreadable header or index above the count`);
  const holes = []; for (let i = 0; i < count; i++) if (!present.has(i)) holes.push(i);
  entries.push([map, count, holes]);
}
const body = entries.map(([map, count, holes]) => `  ${JSON.stringify(map)}: [${count}${holes.map(h => `, ${h}`).join('')}],`).join('\n');
const out = `// Generated by scripts/build-map-registry-seeds.mjs from the original's GObjObjects captures; do not edit.
// Per map: [Num, ...holes], the registry's high-water mark and its freed slots when the capture was taken
// (docs/object-index-captures.md "Runtime spawns"). The order the holes were freed in is not in a dump.
export const MAP_REGISTRY_SEEDS = {
${body}
};

/** {count, freeIndices, holes, exact} for a map, or null. \`exact\` is true when the free list's order is known
 * (at most one hole); with more, the holes are listed ascending and the order is a stated assumption. */
export function mapRegistrySeed(map) {
  const entry = MAP_REGISTRY_SEEDS[String(map ?? '').toLowerCase()];
  if (!entry) return null;
  const [count, ...holes] = entry;
  return { count, freeIndices: holes, holes: holes.length, exact: holes.length <= 1 };
}
`;
const target = path.join(root, 'src/runtime/map-registry-seeds.mjs');
if (check) { const current = existsSync(target) ? await readFile(target, 'utf8') : ''; console.log(current === out ? 'map-registry-seeds.mjs is current' : 'map-registry-seeds.mjs differs'); process.exit(current === out ? 0 : 1); }
await writeFile(target, out);
console.log(`${entries.length} maps; missing: ${JSON.stringify(report)}; with more than one hole: ${entries.filter(e => e[2].length > 1).length}`);
