// Build src/runtime/map-npc-identities.mjs from the original GObjObjects
// captures (docs/object-index-captures.md): for each
// .cache/original-gobjects-<date>-<map>-open.txt, scripts/capture-npc-identities.mjs
// matches every pre-placed Pawn of the map to the capture by class and name.
// 00_Training and 01_NYC_UNATCOIsland keep their own modules (Training's
// table comes from a capture started on the map itself).
//
//   node scripts/build-npc-identities.mjs [--date yyyymmdd] [--jobs 3] [--check]
//
// --check compares the module with a fresh build and writes nothing.
import { execFile } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const argv = process.argv.slice(2);
const flag = (name, fallback) => { const i = argv.indexOf(name); return i < 0 ? fallback : argv[i + 1]; };
const date = flag('--date', '20261001'), jobs = Number(flag('--jobs', 3)), check = argv.includes('--check');
const OWN = new Set(['00_training', '01_nyc_unatcoisland']);
const pattern = new RegExp(`^original-gobjects-${date}-(.+)-open\\.txt$`);
const maps = readdirSync(path.join(root, 'Deus Ex GOTY Edition', 'Maps'))
  .filter(name => /\.dx$/i.test(name)).map(name => name.replace(/\.dx$/i, ''));
const captures = readdirSync(path.join(root, '.cache')).map(name => pattern.exec(name)).filter(Boolean)
  .map(match => ({ file: path.join('.cache', match[0]), map: maps.find(map => map.toLowerCase() === match[1]) }))
  // Multiplayer maps are excluded, as in the map-startup census (deferred).
  .filter(capture => capture.map && !OWN.has(capture.map.toLowerCase()) && !/^dxmp_/i.test(capture.map))
  .sort((a, b) => a.map.localeCompare(b.map));
const run = promisify(execFile);
const tables = {}, problems = [];
const queue = [...captures];
await Promise.all(Array.from({ length: jobs }, async () => {
  for (let capture; (capture = queue.shift());) {
    let result;
    try {
      const { stdout } = await run(process.execPath, [path.join(root, 'scripts', 'capture-npc-identities.mjs'), capture.file, capture.map],
        { cwd: root, maxBuffer: 1 << 26 });
      result = JSON.parse(stdout.trim().split('\n').pop());
    } catch (error) {
      // A map Play cannot boot yet has no table; its speech stays a boundary.
      const reason = /Error: (.*)/.exec(String(error.stderr ?? error.message))?.[1] ?? String(error.message).split('\n')[0];
      problems.push({ map: capture.map, boot: reason });
      console.error(`${capture.map}: boot failed: ${reason}`);
      continue;
    }
    if (result.missing.length) problems.push({ map: capture.map, missing: result.missing });
    tables[capture.map.toLowerCase()] = result.identities;
    console.error(`${capture.map}: ${result.count} pawns${result.missing.length ? `, missing ${result.missing.join(' ')}` : ''}`);
  }
}));
const keys = Object.keys(tables).sort();
const lines = [
  '// Generated by scripts/build-npc-identities.mjs from the original GObjObjects',
  `// captures (.cache/original-gobjects-${date}-<map>-open.txt; each map opened`,
  "// from Training's console in a fresh DeusEx.exe, docs/object-index-captures.md):",
  '// every pre-placed Pawn by name. 00_Training and 01_NYC_UNATCOIsland have',
  '// their own modules.',
  'export const MAP_NPC_IDENTITIES=Object.freeze({',
  ...keys.map(key => `  '${key}':Object.freeze(${JSON.stringify(tables[key]).replace(/"([A-Za-z_][A-Za-z0-9_]*)":/g, '$1:')}),`),
  '});',
  '',
];
const out = path.join(root, 'src', 'runtime', 'map-npc-identities.mjs');
if (check) {
  const same = readFileSync(out, 'utf8') === lines.join('\n');
  console.log(JSON.stringify({ maps: keys.length, same, problems }));
  process.exit(same && !problems.length ? 0 : 1);
}
writeFileSync(out, lines.join('\n'));
console.log(JSON.stringify({ maps: keys.length, pawns: keys.reduce((n, key) => n + Object.keys(tables[key]).length, 0), problems }));
